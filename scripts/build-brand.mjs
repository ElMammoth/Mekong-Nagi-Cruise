#!/usr/bin/env node
/**
 * Brand assets from the single source of truth, src/brand/logo.svg (one path, currentColor).
 *
 *   npm run brand
 *
 * Writes (all committed, regenerated whenever the logo changes):
 * - src/components/brand/logo-data.generated.ts  path data for the inline <Logo> component
 * - src/app/icon.svg          favicon (SVG): white mark on a flag-blue rounded square
 * - src/app/favicon.ico       16, 32 and 48 px PNGs in one .ico
 * - src/app/apple-icon.png    180 px, opaque blue square
 * - public/brand/icon-192.png, icon-512.png   PWA icons (manifest.ts)
 * - public/brand/logo.png     blue mark on white, for the Organization structured data
 * Colours come from the token layer (src/app/globals.css).
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const source = readFileSync("src/brand/logo.svg", "utf8");
const css = readFileSync("src/app/globals.css", "utf8");
const token = (name) => {
  const m = css.match(new RegExp(`--${name}:\\s*(#[0-9a-fA-F]{6})`));
  if (!m) throw new Error(`No colour token --${name}`);
  return m[1];
};
const BLUE = token("color-primary");
const WHITE = token("color-on-primary");

const viewBox = source.match(/viewBox="([^"]+)"/)?.[1];
const d = source.match(/\sd="([^"]+)"/)?.[1];
const strokeWidth = Number(source.match(/stroke-width="([^"]+)"/)?.[1] ?? 0);
if (!viewBox || !d) throw new Error("src/brand/logo.svg must have a viewBox and one path");
const [, , vw, vh] = viewBox.split(/\s+/).map(Number);

// 1 · Data for the inline component
writeFileSync(
  "src/components/brand/logo-data.generated.ts",
  `// Generated by scripts/build-brand.mjs from src/brand/logo.svg. Do not edit.\n` +
    `export const logo = ${JSON.stringify({ viewBox, width: vw, height: vh, strokeWidth, d }, null, 2)} as const;\n`,
);

/** The mark in one colour, fitted (aspect kept) into a size × size square with padding. */
function squareSvg({ size, padding, fg, bg, radius = 0 }) {
  const inner = size - padding * 2;
  const scale = inner / vw; // wide mark: width is the limit
  const h = vh * scale;
  const y = (size - h) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">${
    bg ? `<rect width="${size}" height="${size}" rx="${radius}" fill="${bg}"/>` : ""
  }<g transform="translate(${padding} ${y.toFixed(2)}) scale(${scale.toFixed(5)})"><path fill="${fg}" stroke="${fg}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" d="${d}"/></g></svg>`;
}

const png = (svg, size) => sharp(Buffer.from(svg)).resize(size, size).png().toBuffer();

/** .ico holding PNG images (supported by every current browser). */
function ico(images) {
  const header = Buffer.alloc(6 + images.length * 16);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, data }, i) => {
    const e = 6 + i * 16;
    header.writeUInt8(size >= 256 ? 0 : size, e);
    header.writeUInt8(size >= 256 ? 0 : size, e + 1);
    header.writeUInt16LE(1, e + 4); // colour planes
    header.writeUInt16LE(32, e + 6); // bits per pixel
    header.writeUInt32LE(data.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map((im) => im.data)]);
}

// Square icons: white mark on blue. The mark is wide and short, so the small favicons
// (≤ 64 px) use 6 % padding to keep it as large as possible; larger icons use 12 %.
const icon = (size, radius) =>
  squareSvg({
    size,
    padding: Math.max(1, Math.round(size * (size <= 64 ? 0.06 : 0.12))),
    fg: WHITE,
    bg: BLUE,
    radius,
  });

writeFileSync("src/app/icon.svg", icon(64, 12) + "\n");
const icoSizes = [16, 32, 48];
writeFileSync(
  "src/app/favicon.ico",
  ico(
    await Promise.all(
      icoSizes.map(async (size) => ({
        size,
        data: await png(icon(size, Math.round(size / 6)), size),
      })),
    ),
  ),
);
writeFileSync("src/app/apple-icon.png", await png(icon(180, 0), 180)); // iOS rounds the corners
mkdirSync("public/brand", { recursive: true });
for (const size of [192, 512])
  writeFileSync(`public/brand/icon-${size}.png`, await png(icon(size, 0), size));

// Organization logo: blue mark on white, 600 px wide, aspect kept.
const lw = 600;
const pad = 24;
const lh = Math.round(((lw - pad * 2) / vw) * vh + pad * 2);
const logoSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="${lw}" height="${lh}" viewBox="${-pad * (vw / (lw - pad * 2))} ${-pad * (vw / (lw - pad * 2))} ${vw + 2 * pad * (vw / (lw - pad * 2))} ${vh + 2 * pad * (vw / (lw - pad * 2))}"><rect x="-100" y="-100" width="${vw + 200}" height="${vh + 200}" fill="#ffffff"/><path fill="${BLUE}" stroke="${BLUE}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" d="${d}"/></svg>`;
writeFileSync("public/brand/logo.png", await sharp(Buffer.from(logoSvg)).png().toBuffer());

console.log(
  `brand: logo ${vw}×${vh} → component data, icon.svg, favicon.ico, apple-icon, PWA icons, logo.png`,
);
